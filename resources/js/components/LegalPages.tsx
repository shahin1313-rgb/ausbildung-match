import type { ReactNode } from "react";
import type { LegalConfig, LegalProvider } from "../types";

export type LegalPageKey = "privacy" | "terms" | "impressum" | "resume-retention";

type Props = { page: LegalPageKey; legal: LegalConfig };

const missing = "در تنظیمات محیطی تکمیل شود";
const value = (input: string | null) => input?.trim() || missing;

function Contact({ provider, privacy = false }: { provider: LegalProvider; privacy?: boolean }) {
  return (
    <address className="legal-address">
      <strong>{value(provider.name)}</strong>
      <span>{[provider.street_address, provider.postal_code, provider.city, provider.country].filter(Boolean).join("، ") || missing}</span>
      <span>ایمیل: {value(privacy ? provider.data_protection_email || provider.email : provider.email)}</span>
      {provider.phone && <span>تلفن: {provider.phone}</span>}
    </address>
  );
}

